-- ─── Extension: pgcrypto ─────────────────────────────────────
-- Required for gen_random_uuid() to generate UUID v4 primary keys.
-- Available natively in PostgreSQL 13+ via pgcrypto or pg_catalog.
CREATE EXTENSION IF NOT EXISTS "pgcrypto";


-- ─── Table: Users ────────────────────────────────────────────
-- Stores user accounts for the VinFast O2O platform.
-- OTP is stored hashed (not plaintext) for defense-in-depth.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Users" (

    -- ── Primary Key ─────────────────────────────────────────
    -- UUID v4 generated at DB level as a secure fallback.
    -- Application layer should generate and supply this value.
    "UserId"             UUID            NOT NULL
                                         DEFAULT gen_random_uuid(),

    -- ── Identity & Credentials ──────────────────────────────
    -- Email is the primary login identifier; must be unique and non-null.
    -- Stored in lowercase to prevent duplicate entries for the same address.
    "Email"              VARCHAR(320)    NOT NULL,   -- RFC 5321 max email length

    -- Bcrypt / Argon2id hash of the user password.
    -- NEVER store raw passwords. Application must hash before insert.
    -- VARCHAR(512) accommodates Argon2id output which can be longer than bcrypt's 60 chars.
    "PasswordHash"       VARCHAR(512)    NOT NULL,

    -- ── Email Verification via OTP ──────────────────────────
    -- False by default; set to True only after the user submits
    -- the correct 6-digit OTP within the expiry window.
    "IsEmailConfirmed"   BOOLEAN         NOT NULL    DEFAULT FALSE,

    -- Hashed OTP code (CHAR(6) digit string after hashing becomes ~60 chars).
    -- Store the hash, NOT the raw 6-digit code, to protect against DB leaks.
    -- NULL when no active OTP has been issued.
    "OtpCode"            VARCHAR(512)    NULL,

    -- Absolute UTC timestamp when the OTP becomes invalid.
    -- Application sets this to NOW() + INTERVAL '5 minutes' on OTP generation.
    -- NULL when no active OTP has been issued.
    "OtpExpiry"          TIMESTAMP WITH TIME ZONE    NULL,

    -- ── Audit Fields ────────────────────────────────────────
    -- Immutable creation timestamp in UTC. Set once at INSERT.
    "CreatedAt"          TIMESTAMP WITH TIME ZONE    NOT NULL
                                                     DEFAULT NOW(),

    -- ── Constraints ─────────────────────────────────────────
    CONSTRAINT "PK_Users"
        PRIMARY KEY ("UserId"),

    -- Enforce uniqueness on the normalised (lowercase) email.
    CONSTRAINT "UQ_Users_Email"
        UNIQUE ("Email"),

    -- Ensure OtpExpiry is only set when OtpCode is also set (and vice-versa).
    -- Prevents inconsistent state where one field is NULL and the other is not.
    CONSTRAINT "CHK_Users_Otp_Consistency"
        CHECK (
            ("OtpCode" IS NULL AND "OtpExpiry" IS NULL)
            OR
            ("OtpCode" IS NOT NULL AND "OtpExpiry" IS NOT NULL)
        ),

    -- Guard against obviously invalid OTP expiry dates (must be in the future
    -- relative to account creation, or NULL).
    CONSTRAINT "CHK_Users_OtpExpiry_After_CreatedAt"
        CHECK ("OtpExpiry" IS NULL OR "OtpExpiry" > "CreatedAt")

);


-- ─── Indexes ─────────────────────────────────────────────────

-- PRIMARY login lookup index.
-- Covers: WHERE LOWER("Email") = LOWER($1)
-- Using a functional index on LOWER("Email") ensures case-insensitive
-- login queries use the index without a full table scan.
CREATE UNIQUE INDEX IF NOT EXISTS "UX_Users_Email_Lower"
    ON "Users" (LOWER("Email"));

-- Partial index to quickly find accounts pending email confirmation.
-- Used by scheduled cleanup jobs and admin dashboards.
-- Only indexes rows where IsEmailConfirmed = FALSE (usually a small subset).
CREATE INDEX IF NOT EXISTS "IX_Users_Unconfirmed"
    ON "Users" ("CreatedAt")
    WHERE "IsEmailConfirmed" = FALSE;

-- Partial index to locate accounts with an active (non-expired) OTP.
-- Supports OTP validation queries: WHERE "UserId" = $1 AND "OtpExpiry" > NOW()
CREATE INDEX IF NOT EXISTS "IX_Users_ActiveOtp"
    ON "Users" ("UserId", "OtpExpiry")
    WHERE "OtpCode" IS NOT NULL;


-- ─── Comments (Column Documentation) ────────────────────────
COMMENT ON TABLE  "Users"                      IS 'Core user account table for VinFast O2O Authentication Service.';
COMMENT ON COLUMN "Users"."UserId"             IS 'UUID v4 primary key. Generated by the application layer; DB default is a fallback.';
COMMENT ON COLUMN "Users"."Email"              IS 'Login email address. Stored as-supplied; uniqueness enforced on LOWER(Email).';
COMMENT ON COLUMN "Users"."PasswordHash"       IS 'Argon2id or BCrypt hash of the user password. Raw passwords must NEVER be stored.';
COMMENT ON COLUMN "Users"."IsEmailConfirmed"   IS 'TRUE only after the user has successfully verified their email via OTP.';
COMMENT ON COLUMN "Users"."OtpCode"            IS 'Hashed 6-digit OTP code. NULL when no verification is in progress. Rotate on each new request.';
COMMENT ON COLUMN "Users"."OtpExpiry"          IS 'UTC expiry timestamp of the active OTP. Application sets to NOW() + 5 minutes. NULL when no OTP is active.';
COMMENT ON COLUMN "Users"."CreatedAt"          IS 'Immutable UTC timestamp of account creation.';
