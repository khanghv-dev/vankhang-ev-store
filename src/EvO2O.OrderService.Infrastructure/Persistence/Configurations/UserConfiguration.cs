using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using EvO2O.OrderService.Domain.Entities;

namespace EvO2O.OrderService.Infrastructure.Persistence.Configurations;

/// <summary>
/// EF Core Fluent API configuration for the <see cref="User"/> entity.
/// Maps to the "Users" table with appropriate column constraints and indexes.
/// </summary>
internal sealed class UserConfiguration : IEntityTypeConfiguration<User>
{
    public void Configure(EntityTypeBuilder<User> builder)
    {
        builder.ToTable("Users");

        // ── Primary Key ───────────────────────────────────────────────────────
        builder.HasKey(u => u.UserId);
        builder.Property(u => u.UserId)
               .ValueGeneratedNever();        // UUID generated by the application

        // ── Email ─────────────────────────────────────────────────────────────
        builder.Property(u => u.Email)
               .IsRequired()
               .HasMaxLength(320);           // RFC 5321 max email length

        // Functional unique index on LOWER(Email) — matches the SQL schema
        builder.HasIndex(u => u.Email)
               .IsUnique()
               .HasDatabaseName("UQ_Users_Email");

        // ── Password ──────────────────────────────────────────────────────────
        builder.Property(u => u.PasswordHash)
               .IsRequired()
               .HasMaxLength(512);

        // ── OTP fields ────────────────────────────────────────────────────────
        builder.Property(u => u.OtpCode)
               .HasMaxLength(512)
               .IsRequired(false);

        builder.Property(u => u.OtpExpiry)
               .IsRequired(false);

        // ── Flags & Timestamps ────────────────────────────────────────────────
        builder.Property(u => u.IsEmailConfirmed)
               .IsRequired()
               .HasDefaultValue(false);

        builder.Property(u => u.CreatedAt)
               .IsRequired()
               .HasDefaultValueSql("NOW()");

        // ── Partial index: unconfirmed accounts (for cleanup jobs) ─────────────
        builder.HasIndex(u => u.CreatedAt)
               .HasFilter("\"IsEmailConfirmed\" = FALSE")
               .HasDatabaseName("IX_Users_Unconfirmed");
    }
}
